#!/usr/bin/env python3
"""Builds the Mafia Night wordmark as one SVG from the real Limelight outlines, with blood drips that start
inside the letter bottoms. Writes public/js/wordmark.js (and refreshes the splash copy in public/index.html).
Usage: python3 tools/build-wordmark.py <limelight-latin-400-normal.woff>   (needs fontTools + brotli/zlib woff)"""
import sys, re, json
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

f = TTFont(sys.argv[1]); gs = f.getGlyphSet(); cm = f.getBestCmap()
ASC, ROW_GAP = 1479, 560          # cap height, vertical room for drips between the rows
def row(word, y0, drips):
    x, d = 0, []
    for ch in word:
        g = gs[cm[ord(ch)]]; p = SVGPathPen(gs)
        g.draw(TransformPen(p, (1, 0, 0, -1, x, y0))); d.append(p.getCommands()); x += g.width
    return ' '.join(d), x
r1, w1 = row('MAFIA', ASC, None)
r2, w2 = row('NIGHT', ASC * 2 + ROW_GAP, None)
W = max(w1, w2); H = ASC * 2 + ROW_GAP + 760
# (word row baseline, x of a drip inside a letter bottom, stroke width, length). Fixed, so renders are stable.
B1, B2 = ASC, ASC * 2 + ROW_GAP
D = [(B1, 1560, 100, 400), (B1, 2900, 90, 230), (B1, 3600, 110, 470), (B1, 4800, 96, 260), (B1, 6250, 100, 320),
     (B2, 200, 84, 560), (B2, 1850, 100, 420), (B2, 3350, 110, 720), (B2, 4300, 100, 480), (B2, 6000, 104, 640)]
def drip(i, b, x, w, l):
    top, r = b - 70, int(w * 0.9)   # a stem with a round bulb on the end
    return f'<path class="dr" style="--i:{i}" d="M{x} {top}h{w}v{l - 2 * r}a{r} {r} 0 1 1 -{w} 0z"/>'
drips = ''.join(drip(i, *t) for i, t in enumerate(D))
svg = (f'<svg class="wordmark-svg" viewBox="0 0 {W} {H}" aria-hidden="true" focusable="false">'
       f'<defs><linearGradient id="wmg" x1="0" y1="0" x2="0" y2="1"><stop offset=".62" stop-color="#FFF4E6"/><stop offset="1" stop-color="#B3121F"/></linearGradient></defs>'
       f'<path class="wm-l" fill="url(#wmg)" d="{r1}"/><path class="wm-l wm-l2" fill="url(#wmg)" d="{r2}"/>'
       f'<g class="wm-blood">{drips}</g></svg>')
open('public/js/wordmark.js', 'w').write('// Generated by tools/build-wordmark.py from Limelight glyph outlines. Do not edit by hand.\n'
    'export const WORDMARK_SVG = ' + json.dumps(svg) + ';\n')
h = open('public/index.html').read()
h2 = re.sub(r'<h1 class="wordmark">.*?</h1>', lambda m: '<h1 class="wordmark"><span class="sr-only">Mafia Night</span>' + svg + '</h1>', h, count=1)
open('public/index.html', 'w').write(h2); print(W, H, len(svg))
