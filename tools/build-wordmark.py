#!/usr/bin/env python3
"""Builds the Mafia Night wordmark as one SVG from the real Limelight outlines, with blood drips that start
inside the letter bottoms. Writes public/js/wordmark.js (and refreshes the splash copy in public/index.html).
Usage: python3 tools/build-wordmark.py <limelight-latin-400-normal.woff>   (needs fontTools + brotli/zlib woff)"""
import sys, re, json
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

f = TTFont(sys.argv[1]); gs = f.getGlyphSet(); cm = f.getBestCmap()
ASC, ROW_GAP = 1479, 560          # cap height, vertical room for drips between the rows
def row(word, y0, drips):
    x, d = 0, []
    for ch in word:
        g = gs[cm[ord(ch)]]; p = SVGPathPen(gs)
        g.draw(TransformPen(p, (1, 0, 0, -1, x, y0))); d.append(p.getCommands()); x += g.width
    return ' '.join(d), x
r1, w1 = row('MAFIA', ASC, None)
r2, w2 = row('NIGHT', ASC * 2 + ROW_GAP, None)
W = max(w1, w2); H = ASC * 2 + ROW_GAP + 760
# (word row baseline, x of a drip inside a letter bottom, stroke width, length). Fixed, so renders are stable.
B1, B2 = ASC, ASC * 2 + ROW_GAP
D = [(B1, 1560, 100, 400), (B1, 2900, 90, 230), (B1, 3600, 110, 470), (B1, 4800, 96, 260), (B1, 6250, 100, 320),
     (B2, 200, 84, 560), (B2, 1850, 100, 420), (B2, 3350, 110, 720), (B2, 4300, 100, 480), (B2, 6000, 104, 640)]
def drip(i, b, x, w, l):
    # Blood: a wide base fused into the letter bottom, narrowing to a thin neck, then swelling into a teardrop tip.
    # Neck and tip vary per drip (i). Each drip is its own small <svg> over the letters (percent of the wordmark box):
    # transforms on SVG children are not composited by Chrome, on an HTML-level <svg> they are.
    cx, top = x + w / 2, b - 70
    bw = w * (0.78 + 0.06 * (i % 3))       # half width of the base
    nw = w * (0.17 + 0.03 * (i % 4))       # half width of the neck
    r = w * (0.5 + 0.05 * (i % 3))         # radius of the tip
    c = top + l - r                        # centre of the tip
    n0, n1 = top + l * 0.34, c - r * 1.9   # neck runs from n0 to n1, then the tip swells
    half = max(bw, r)
    X0, Y0, VW, VH = cx - half, top, 2 * half, l
    f = lambda v: f'{v:.0f}'
    pt = lambda px, py: f'{f(px - X0)} {f(py - Y0)}'
    d = (f'M{pt(cx - bw, top)}H{f(cx + bw - X0)}'
         f'C{pt(cx + bw * .7, top + l * .1)} {pt(cx + nw * 1.5, top + l * .2)} {pt(cx + nw, n0)}'
         f'C{pt(cx + nw * .9, (n0 + n1) / 2)} {pt(cx + nw * 1.2, n1 - r * .3)} {pt(cx + r * .55, c - r * .95)}'
         f'C{pt(cx + r * .95, c - r * .6)} {pt(cx + r, c - r * .2)} {pt(cx + r, c)}'
         f'A{f(r)} {f(r)} 0 0 1 {pt(cx - r, c)}'
         f'C{pt(cx - r, c - r * .2)} {pt(cx - r * .95, c - r * .6)} {pt(cx - r * .55, c - r * .95)}'
         f'C{pt(cx - nw * 1.2, n1 - r * .3)} {pt(cx - nw * .9, (n0 + n1) / 2)} {pt(cx - nw, n0)}'
         f'C{pt(cx - nw * 1.5, top + l * .2)} {pt(cx - bw * .7, top + l * .1)} {pt(cx - bw, top)}Z')
    pc = lambda v, t: f'{v / t * 100:.3f}%'
    return (f'<svg class="dr-svg" style="--i:{i};left:{pc(X0, W)};top:{pc(Y0, H)};width:{pc(VW, W)};height:{pc(VH, H)}" '
            f'viewBox="0 0 {f(VW)} {f(VH)}" preserveAspectRatio="none" focusable="false"><g class="wm-blood"><path class="dr" d="{d}"/></g></svg>')
drips = '<span class="wm-drips" aria-hidden="true">' + ''.join(drip(i, *t) for i, t in enumerate(D)) + '</span>'
svg = (f'<svg class="wordmark-svg" viewBox="0 0 {W} {H}" aria-hidden="true" focusable="false">'
       f'<defs><linearGradient id="wmg" x1="0" y1="0" x2="0" y2="1"><stop offset=".62" stop-color="#FFF4E6"/><stop offset="1" stop-color="#B3121F"/></linearGradient></defs>'
       f'<path class="wm-l" fill="url(#wmg)" d="{r1}"/><path class="wm-l wm-l2" fill="url(#wmg)" d="{r2}"/>'
       '</svg>')
open('public/js/wordmark.js', 'w').write('// Generated by tools/build-wordmark.py from Limelight glyph outlines. Do not edit by hand.\n'
    'export const WORDMARK_SVG = ' + json.dumps(svg) + ';\nexport const WORDMARK_DRIPS = ' + json.dumps(drips) + ';\n')
h = open('public/index.html').read()
h2 = re.sub(r'<h1 class="wordmark">.*?</h1>', lambda m: '<h1 class="wordmark"><span class="sr-only">Mafia Night</span>' + svg + drips + '</h1>', h, count=1)
open('public/index.html', 'w').write(h2); print(W, H, len(svg))
