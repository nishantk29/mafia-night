  log: ['ph', 'scroll-bold'],
  'log-on': ['ph', 'scroll-fill'],
  moon: ['ph', 'moon-stars-bold'],
  sun: ['ph', 'sun-horizon-bold'],
  cards: ['ph', 'cards-bold'],
  phone: ['ph', 'device-mobile-bold'],
  skull: ['ph', 'skull-bold'],
  shield: ['ph', 'shield-bold'],
  save: ['ph', 'lifebuoy-bold'],
