// Role icon sprite: one <g id="name"> per game-icons glyph, drawn on the 512x512 grid that art.js's ico() uses.
// The app draws an icon with <svg viewBox="0 0 512 512"><use href="/icons/roles.svg#name"/></svg>, so the 285 KB of
// glyph data loads only when the first icon is on screen (and is precached by the service worker), not at startup.
export const SPRITE_PATH = '/icons/roles.svg';
export function toSprite(data) {
  const names = Object.keys(data).sort();
  for (const n of names) if (!/^[a-z0-9-]+$/.test(n)) throw new Error(`icon name not safe for an id: ${n}`);
  const body = names.map((n) => `<g id="${n}">${data[n]}</g>`).join('\n');
  return `<svg xmlns="http://www.w3.org/2000/svg"><!-- GENERATED by scripts/build-assets.mjs. Icons: game-icons.net (CC BY 3.0). -->\n<defs>\n${body}\n</defs></svg>\n`;
}
