// Builds the generated asset modules:
//   public/icons/roles.svg     SVG sprite of the game-icons used by role_icons.js (scripts/icon-sprite.mjs)
//   public/js/art_manifest.js  which role portraits exist in public/art/<roleId>.(webp|png|jpg)
//   public/fonts/*.woff2       self-hosted fonts copied from node_modules
// Run: npm run assets
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pub = (...p) => path.join(root, 'public', ...p);

// ---- icons ----
const { ROLE_ICON } = await import(pathToFileURL(pub('js/role_icons.js')).href + '?t=' + Date.now());
const set = JSON.parse(fs.readFileSync(path.join(root, 'node_modules/@iconify-json/game-icons/icons.json'), 'utf8'));
const used = [...new Set(Object.values(ROLE_ICON))].sort();
const missing = used.filter((n) => !set.icons[n] && !set.aliases?.[n]);
if (missing.length) { console.error('Unknown icon names:', missing.join(', ')); process.exit(1); }
const data = {};
for (const n of used) {
  const ic = set.icons[n] || set.icons[set.aliases[n].parent];
  data[n] = ic.body;
}
const { toSprite } = await import('./icon-sprite.mjs');
fs.writeFileSync(pub('icons/roles.svg'), toSprite(data));
console.log(`icons: ${used.length} used for ${Object.keys(ROLE_ICON).length} roles`);

// ---- art manifest ----
const artDir = pub('art');
const art = fs.existsSync(artDir) ? fs.readdirSync(artDir).filter((f) => /\.(webp|png|jpe?g)$/i.test(f)) : [];
const map = Object.fromEntries(art.map((f) => [f.replace(/\.[^.]+$/, ''), f]));
fs.writeFileSync(pub('js/art_manifest.js'), `// GENERATED by scripts/build-assets.mjs: role portraits found in public/art/\nexport const ART = ${JSON.stringify(map)};\n`);
console.log(`portraits: ${art.length}`);

// ---- fonts ----
// All SIL OFL 1.1. Limelight (display), Alegreya Sans (UI/body), Alegreya italic (spoken lines).
const fonts = [
  ...[400, 500, 700, 800].map((w) => [`@fontsource/alegreya-sans/files/alegreya-sans-latin-${w}-normal.woff2`, `alegreya-sans-${w}.woff2`]),
  ['@fontsource-variable/alegreya/files/alegreya-latin-wght-italic.woff2', 'alegreya-italic-var.woff2'],
];
fs.mkdirSync(pub('fonts'), { recursive: true });
for (const [src, dst] of fonts) fs.copyFileSync(path.join(root, 'node_modules', src), pub('fonts', dst));
console.log('fonts: copied', fonts.length);
